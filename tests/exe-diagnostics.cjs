const assert = require('node:assert/strict');
const { unexpectedExeDiagnostics } = require('./fixtures/exe-diagnostics.cjs');
const executable = 'C:\\TEMP\\D4 中文 space [test]\\Pi GUI.exe';
const warning = `Warning: Cannot load "@napi-rs/canvas" package: "Error: Cannot find module '@napi-rs/canvas'\nRequire stack:\n- ${executable}".\n`;
let passed = 0;
const check = (name, input, expected) => {
  assert.equal(unexpectedExeDiagnostics({ executable, stdout: '', stderr: '', exit: null, ...input }), expected, name);
  passed++; console.log('ok ' + name);
};
check('clean outputs', {}, null);
check('exact caught optional canvas warning in stderr', { stderr: warning }, null);
check('CRLF warning', { stderr: warning.replaceAll('\n', '\r\n') }, null);
check('identical repeated known warning', { stderr: warning + warning }, null);
check('known warning cannot whitelist stdout', { stdout: warning }, 'unexpected_error_output');
check('unknown missing dependency', { stderr: warning.replaceAll('@napi-rs/canvas', 'unknown-module') }, 'unexpected_error_output');
check('wrong executable stack', { stderr: warning.replace(executable, 'C:\\foreign\\Pi GUI.exe') }, 'unexpected_error_output');
check('extra stack frame', { stderr: warning.replace('".\n', '\n- C:\\foreign\\module.cjs".\n') }, 'unexpected_error_output');
check('different caught exception', { stderr: warning.replace('Cannot find module', 'Unexpected failure in module') }, 'unexpected_error_output');
check('malformed warning', { stderr: warning.replace('".\n', '". trailing text\n') }, 'unexpected_error_output');
check('real stderr error alongside known warning', { stderr: warning + 'TypeError: real failure\n    at execute (server.cjs:1:1)\n' }, 'unexpected_error_output');
check('real stdout error alongside known warning', { stderr: warning, stdout: 'Error: real failure\n' }, 'unexpected_error_output');
check('old throw detection retained', { stdout: 'throw unexpected\n' }, 'unexpected_error_output');
check('native fatal error', { stderr: warning + 'FATAL ERROR: allocation failure\n' }, 'unexpected_error_output');
check('unhandled rejection without Error colon', { stderr: 'UnhandledPromiseRejection: reason\n' }, 'unexpected_error_output');
check('premature success exit', { stderr: warning, exit: { code: 0, signal: null } }, 'unexpected_exit');
check('premature nonzero exit', { stderr: warning, exit: { code: 1, signal: null } }, 'unexpected_exit');
check('premature signal exit', { exit: { code: null, signal: 'SIGTERM' } }, 'unexpected_exit');
check('real error still detected with premature exit', { stderr: warning + 'Error: fatal\n', exit: { code: 1, signal: null } }, 'unexpected_error_output');
console.log(`EXE diagnostics: ${passed}/${passed}; pure classification, not packaged evidence`);
