const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');

let checks = 0;
function check(name, actual, expected = true) {
  assert.deepEqual(actual, expected, name);
  checks++;
  console.log(`  ok ${name}`);
}
const fixture = () => ({
  documentId: 'doc-1', schemaVersion: 1, revision: 2, title: '流程图', boundSessionId: 'session-1', appliedOps: [],
  graph: { nodes: [{ id: 'n1', label: '开始', x: 0, y: 0 }, { id: 'n2', label: '处理', x: 200, y: 0 },
    { id: 'n3', label: '结束', x: 400, y: 0 }],
  edges: [{ id: 'e1', from: 'n1', to: 'n2' }, { id: 'e2', from: 'n2', to: 'n3', label: '完成' }] },
});

async function main() {
  const { mountCollabCanvas } = await import('../public/collab-canvas.js');
  const { mountCollabProposal } = await import('../public/collab-proposal.js');
  const dom = new JSDOM('<main><div id="canvas"></div><div id="proposal"></div></main>');
  const win = dom.window;
  const style = win.document.createElement('style');
  style.textContent = fs.readFileSync(path.join(__dirname, '../public/tokens.css'), 'utf8') + '\n' + fs.readFileSync(path.join(__dirname, '../public/collab.css'), 'utf8');
  win.document.head.append(style);
  const host = win.document.querySelector('#canvas');
  const proposalHost = win.document.querySelector('#proposal');
  const q = selector => host.querySelector(selector);
  const button = name => [...host.querySelectorAll('button')].find(el => el.textContent === name);
  const fire = (el, type, init = {}) => el.dispatchEvent(new win.MouseEvent(type, { bubbles: true, cancelable: true, ...init }));
  const key = (el, value, init = {}) => el.dispatchEvent(new win.KeyboardEvent('keydown', { key: value, bubbles: true, cancelable: true, ...init }));
  const calls = [];
  let undo = 0, redo = 0;
  let doc = fixture();
  const original = JSON.stringify(doc);
  const canvas = mountCollabCanvas(host, { document: doc, onOperations: ops => calls.push(ops), onUndo: () => undo++, onRedo: () => redo++ });
  check('three nodes', host.querySelectorAll('.collab-node').length, 3);
  check('two directed edges', host.querySelectorAll('.collab-edge').length, 2);
  check('arrow marker present', !!q('marker path'));
  check('canvas keyboard focus', q('svg').getAttribute('tabindex'), '0');
  check('narrow toolbar wraps', win.getComputedStyle(q('.collab-toolbar')).flexWrap, 'wrap');
  check('narrow inspector permits shrinking', win.getComputedStyle(q('.collab-edit-form label')).minWidth, '0');
  const darkCanvas = win.getComputedStyle(win.document.documentElement).getPropertyValue('--ui-canvas');
  win.document.documentElement.dataset.theme = 'light';
  check('light theme token differs', win.getComputedStyle(win.document.documentElement).getPropertyValue('--ui-canvas') !== darkCanvas);
  win.document.documentElement.dataset.theme = 'dark';
  check('dark theme token restored', win.getComputedStyle(win.document.documentElement).getPropertyValue('--ui-canvas'), darkCanvas);
  check('mount never writes', calls.length, 0);
  fire(q('[data-node-id="n2"]'), 'click');
  check('selection accessible', q('[data-node-id="n2"]').getAttribute('aria-pressed'), 'true');
  q('svg').focus(); key(q('svg'), 'Enter');
  check('Enter edits pointer-selected node', win.document.activeElement, q('[name="label"]'));
  const label = q('[name="label"]');
  label.value = '<img src=x onerror=alert(1)>';
  fire(q('.collab-edit-form'), 'submit');
  check('label edit emits intent only', calls.pop(), [{ type: 'node.update', params: { id: 'n2', label: '<img src=x onerror=alert(1)>' } }]);
  label.value = '  ';
  fire(q('.collab-edit-form'), 'submit');
  check('blank node label refused', calls.length, 0);
  fire(button('新增节点'), 'click');
  const added = calls.pop()[0];
  check('add has correct type', added.type, 'node.add');
  check('add valid bounded id', /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/.test(added.params.id));
  check('no op authority assigned', Object.keys(added).sort(), ['params', 'type']);
  const node = q('[data-node-id="n1"]');
  const initialZoom = Number(q('.collab-viewport').getAttribute('transform').match(/scale\(([^)]+)/)[1]);
  fire(node, 'pointerdown', { clientX: 40, clientY: 40, button: 0 });
  fire(win.document, 'pointermove', { clientX: 70, clientY: 60 });
  fire(win.document, 'pointermove', { clientX: 90, clientY: 70 });
  check('drag preview emits nothing', calls.length, 0);
  fire(win.document, 'pointerup', { clientX: 90, clientY: 70 });
  check('drag emits once at end in graph coordinates', calls.splice(0), [[{ type: 'node.update', params: { id: 'n1', x: Math.round(50 / initialZoom), y: Math.round(30 / initialZoom) } }]]);
  check('input graph unchanged', JSON.stringify(doc), original);
  fire(q('[data-node-id="n1"]'), 'pointerdown', { clientX: 0, clientY: 0 });
  fire(win.document, 'pointermove', { clientX: 20, clientY: 20 });
  fire(win.document, 'pointercancel');
  check('cancel emits nothing', calls.length, 0);
  fire(q('[data-node-id="n1"]'), 'click');
  q('[name="edgeTarget"]').value = 'n3';
  fire(q('.collab-connect-form'), 'submit');
  const edge = calls.pop()[0];
  check('edge intent endpoints', { type: edge.type, from: edge.params.from, to: edge.params.to }, { type: 'edge.add', from: 'n1', to: 'n3' });
  q('[name="edgeTarget"]').value = 'n2';
  fire(q('.collab-connect-form'), 'submit');
  check('duplicate edge refused', calls.length, 0);
  fire(q('[data-edge-id="e2"]'), 'click');
  q('[name="label"]').value = '';
  fire(q('.collab-edit-form'), 'submit');
  check('edge label clear intent', calls.pop(), [{ type: 'edge.update', params: { id: 'e2', label: null } }]);
  fire(button('删除所选'), 'click');
  check('delete awaits confirmation', calls.length, 0);
  fire(button('取消'), 'click');
  check('cancel deletion does not write', calls.length, 0);
  fire(button('删除所选'), 'click'); fire(button('确认删除'), 'click');
  check('edge deletion intent', calls.pop(), [{ type: 'edge.remove', params: { id: 'e2' } }]);
  fire(q('[data-node-id="n2"]'), 'click');
  key(q('[data-node-id="n2"]'), 'Delete');
  fire(button('确认删除'), 'click');
  check('node delete atomic edges first', calls.pop(), [{ type: 'edge.remove', params: { id: 'e1' } }, { type: 'edge.remove', params: { id: 'e2' } }, { type: 'node.remove', params: { id: 'n2' } }]);
  canvas.update({ document: doc, canUndo: true, canRedo: true });
  fire(button('撤销'), 'click');
  key(q('svg'), 'z', { ctrlKey: true, shiftKey: true });
  check('controlled undo callback', undo, 1);
  check('controlled redo callback', redo, 1);
  canvas.update({ document: doc, canUndo: false, canRedo: false });
  key(q('svg'), 'z', { ctrlKey: true });
  check('cleared history disables callback', undo, 1);
  const beforeZoom = q('.collab-viewport').getAttribute('transform');
  fire(button('放大'), 'click');
  check('zoom changes viewport', q('.collab-viewport').getAttribute('transform') !== beforeZoom);
  const zoomed = q('.collab-viewport').getAttribute('transform');
  key(q('svg'), 'ArrowRight');
  check('keyboard pan', q('.collab-viewport').getAttribute('transform') !== zoomed);
  key(q('[data-node-id="n3"]'), 'ArrowDown');
  check('keyboard node move', calls.pop(), [{ type: 'node.update', params: { id: 'n3', x: 400, y: 10 } }]);
  canvas.update({ document: doc, readOnly: true, canUndo: true });
  check('readonly visible', q('.collab-status').textContent.includes('只读'));
  check('readonly edit disabled', button('新增节点').disabled);
  fire(q('[data-node-id="n1"]'), 'pointerdown');
  fire(win.document, 'pointermove', { clientX: 50, clientY: 30 });
  fire(win.document, 'pointerup');
  key(q('svg'), 'z', { ctrlKey: true });
  check('readonly blocks mutations and history', [calls.length, undo], [0, 1]);
  canvas.update({ document: doc, readOnly: false, busy: true });
  check('busy accessible', host.firstChild.getAttribute('aria-busy'), 'true');
  check('busy blocks add', button('新增节点').disabled);
  canvas.update({ document: doc, busy: false, error: 'collab_revision_conflict' });
  check('error alert', q('[role="alert"]').textContent.includes('collab_revision_conflict'));
  check('error does not enable writes', button('新增节点').disabled);
  canvas.update({ document: { ...doc, graph: { nodes: [{ id: 'bad', label: 'bad', x: NaN, y: 0 }], edges: [] } }, error: null });
  check('invalid input fails closed', button('新增节点').disabled);
  check('invalid input not rendered', host.querySelectorAll('.collab-node').length, 0);
  doc = fixture();
  doc.graph.nodes[0].label = '<script>alert(1)</script>';
  canvas.update({ document: doc });
  check('markup rendered as text', host.querySelectorAll('script,img').length, 0);
  check('full label accessible', q('[data-node-id="n1"] title').textContent, doc.graph.nodes[0].label);
  fire(q('[data-node-id="n1"]'), 'dblclick');
  check('edit focus', win.document.activeElement, q('[name="label"]'));
  key(q('[name="label"]'), 'Delete');
  check('typing delete not intercepted', q('.collab-confirm').hidden);
  canvas.update({ document: { ...fixture(), graph: { ...fixture().graph, nodes: [{ id: 'blank', label: ' ', x: 0, y: 0 }], edges: [] } } });
  check('whitespace-only label fails closed', host.querySelectorAll('.collab-node').length, 0);
  const hundred = fixture();
  hundred.graph.nodes = Array.from({ length: 100 }, (_, i) => ({ id: `n${i}`, label: '长文本'.repeat(30), x: i % 10 * 180, y: Math.floor(i / 10) * 100 }));
  hundred.graph.edges = [];
  canvas.update({ document: hundred, error: null });
  check('100 nodes render', host.querySelectorAll('.collab-node').length, 100);
  check('long text bounded in SVG', [...host.querySelectorAll('.collab-node text')].every(el => el.textContent.length < 100));
  const savedButton = button('新增节点');
  canvas.destroy();
  fire(savedButton, 'click');
  fire(win.document, 'pointerup');
  check('destroy clears DOM', host.childNodes.length, 0);
  check('destroy detaches callbacks', calls.length, 0);
  canvas.destroy();
  let resolveDelete;
  const reopened = mountCollabCanvas(host, { document: fixture(), onOperations: ops => calls.push(ops), confirmDelete: () => new Promise(resolve => { resolveDelete = resolve; }) });
  fire(q('[data-node-id="n1"]'), 'click');
  fire(button('删除所选'), 'click');
  reopened.update({ document: { ...fixture(), revision: 3 } });
  resolveDelete(true);
  await Promise.resolve();
  check('late delete confirmation invalidated by update', calls.length, 0);
  reopened.destroy();
  let rejectOperation;
  const asyncCanvas = mountCollabCanvas(host, { document: fixture(), onOperations: () => new Promise((resolve, reject) => { rejectOperation = reject; }) });
  fire(button('新增节点'), 'click');
  asyncCanvas.update({ document: { ...fixture(), documentId: 'doc-2' } });
  rejectOperation(new Error('old failure'));
  await Promise.resolve(); await Promise.resolve();
  check('late callback failure cannot affect new document', q('.collab-error').hidden);
  asyncCanvas.update({ document: null });
  check('null document safely disabled', button('新增节点').disabled);
  asyncCanvas.destroy();

  const dense = fixture();
  dense.graph.nodes = Array.from({ length: 51 }, (_, i) => ({ id: `dense${i}`, label: `节点${i}`, x: i * 10, y: i * 10 }));
  dense.graph.edges = Array.from({ length: 50 }, (_, i) => ({ id: `link${i}`, from: 'dense0', to: `dense${i + 1}` }));
  const denseCanvas = mountCollabCanvas(host, { document: dense, onOperations: ops => calls.push(ops) });
  fire(q('[data-node-id="dense0"]'), 'click'); fire(button('删除所选'), 'click');
  check('over-limit atomic deletion blocked', calls.length, 0);
  check('over-limit deletion explains batching', q('.collab-error').textContent.includes('50'));
  denseCanvas.destroy();

  const actions = [];
  const proposal = mountCollabProposal(proposalHost, { onAccept: id => actions.push(['accept', id]), onReject: id => actions.push(['reject', id]), onRegenerate: id => actions.push(['regenerate', id]) });
  proposal.update({ document: doc, proposal: null, preview: null });
  check('honest no source empty state', proposalHost.textContent.includes('尚未接入可信 Agent 建议来源'));
  const suggestion = { proposalId: 'p1', schemaVersion: 1, documentId: doc.documentId, baseRevision: 2, sessionId: doc.boundSessionId, rationale: '<b>建议</b>', ops: [{ opId: 'a1', type: 'node.update', baseRevision: 2, actor: 'agent', params: { id: 'n1', label: '起点' } }] };
  const preview = { diff: [{ opId: 'a1', type: 'node.update', summary: '<img>更新开始' }], resultingRevision: 3, nodeCount: 3, edgeCount: 2 };
  const snapshot = JSON.stringify({ doc, suggestion, preview });
  proposal.update({ document: doc, proposal: suggestion, preview });
  check('proposal update never writes', actions.length, 0);
  check('proposal safely renders text', proposalHost.querySelectorAll('b,img').length, 0);
  check('proposal diff visible', proposalHost.textContent.includes('<img>更新开始'));
  const pbutton = name => [...proposalHost.querySelectorAll('button')].find(el => el.textContent === name);
  fire(pbutton('接受建议'), 'click');
  fire(pbutton('拒绝建议'), 'click');
  fire(pbutton('重新生成'), 'click');
  check('proposal explicit callbacks only', actions.splice(0), [['accept', 'p1'], ['reject', 'p1'], ['regenerate', 'p1']]);
  check('preview never mutates inputs', JSON.stringify({ doc, suggestion, preview }), snapshot);
  proposal.update({ document: doc, proposal: suggestion, preview, readOnly: true });
  check('readonly disables proposal actions', [...proposalHost.querySelectorAll('button')].every(el => el.disabled));
  proposal.update({ document: { ...doc, revision: 3 }, proposal: suggestion, preview, readOnly: false });
  check('stale suggestion conflict visible', proposalHost.textContent.includes('版本冲突'));
  check('stale suggestion accept disabled', pbutton('接受建议').disabled);
  proposal.update({ document: doc, proposal: suggestion, preview: null });
  check('missing preview accept disabled', pbutton('接受建议').disabled);
  proposal.update({ document: doc, proposal: { ...suggestion, sessionId: 'other-session' }, preview });
  check('wrong session actions disabled', [...proposalHost.querySelectorAll('button')].every(el => el.disabled));
  proposal.update({ document: doc, proposal: suggestion, preview: { ...preview, diff: [{ ...preview.diff[0], opId: 'wrong' }] } });
  check('mismatched preview not accepted', pbutton('接受建议').disabled);
  proposal.update({ document: doc, proposal: suggestion, preview, busy: true });
  check('proposal busy blocks actions', [...proposalHost.querySelectorAll('button')].every(el => el.disabled));
  const detached = pbutton('接受建议');
  proposal.destroy();
  fire(detached, 'click');
  check('proposal destroy clears DOM', proposalHost.childNodes.length, 0);
  check('proposal destroyed action inert', actions.length, 0);
  let rejectProposal;
  const asyncProposal = mountCollabProposal(proposalHost, { onAccept: () => new Promise((resolve, reject) => { rejectProposal = reject; }) });
  asyncProposal.update({ document: doc, proposal: suggestion, preview });
  fire(pbutton('接受建议'), 'click');
  asyncProposal.update({ document: { ...doc, revision: 3 }, proposal: suggestion, preview });
  rejectProposal(new Error('stale failure')); await Promise.resolve(); await Promise.resolve();
  check('late proposal failure cannot overwrite new projection', proposalHost.querySelector('[role="alert"]').hidden);
  asyncProposal.destroy();
  dom.window.close();
  console.log(`\ncollab-canvas: ${checks}/${checks} passed`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
